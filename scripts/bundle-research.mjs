import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const shared=['source-policy.mjs','research-validation.mjs','research-workflow.mjs','deepseek-search.mjs','ai-extraction.mjs'].map(n=>read('supabase/functions/_shared/'+n).replaceAll('export ',''));
const main=read('supabase/functions/research/index.ts').replace(/^import .*_shared.*;\r?\n/gm,'');
mkdirSync(new URL('supabase/dashboard/',root),{recursive:true});
writeFileSync(new URL('supabase/dashboard/index.ts',root),'// Generated by scripts/bundle-research.mjs. Edit the original function files.\n'+shared.join('\n')+'\n'+main);
console.log('Generated supabase/dashboard/index.ts');

