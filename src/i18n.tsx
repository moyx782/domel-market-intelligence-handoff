const extra:Record<string,string>={};
export function registerMessages(messages:Record<string,string>){
 Object.assign(extra,messages);
}

const I18n=createContext<{
 lang:Lang;
 setLang:(lang:Lang)=>void;
 t:(text:string,vars?:Record<string,string|number>)=>string;
}>({lang:'en',setLang:()=>{},t:text=>text});

function fill(text:string,vars?:Record<string,string|number>){
 return vars?text.replace(/\{(\w+)\}/g,(match,key)=>key in vars?String(vars[key]):match):text;
}

export function locale(lang:Lang){
 return lang==='zh'?'zh-CN':'en-GB';
}

export function I18nProvider({children}:{children:ReactNode}){
 const [lang,setLangState]=useState<Lang>(()=>{
  try{
   const saved=localStorage.getItem('domel.lang');
   if(saved==='zh'||saved==='en')return saved;
  }catch{}
  return typeof navigator!=='undefined'&&navigator.language.toLowerCase().startsWith('zh')?'zh':'en';
 });
 const setLang=(next:Lang)=>{
  setLangState(next);
  try{localStorage.setItem('domel.lang',next);}catch{}
 };
 useEffect(()=>{
  document.documentElement.lang=locale(lang);
 },[lang]);
 const value=useMemo(()=>({
  lang,
  setLang,
  t:(text:string,vars?:Record<string,string|number>)=>fill(lang==='zh'?(zh[text]??extra[text]??text):text,vars),
 }),[lang]);
 return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n(){
 return useContext(I18n);
}
